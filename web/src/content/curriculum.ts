export const curriculum: Section[] = seeds.map((seed, index) => {
  const id = `s${pad(index + 1)}`
  return {
    id,
    index: index + 1,
    title: seed.title,
    tagline: seed.tagline,
    description: seed.description,
    accent: seed.accent,
    icon: seed.icon,
    chapters: buildChapters(id, seed.chapters),
  }
})

export const sectionById = new Map(curriculum.map((section) => [section.id, section]))

export const allLessonRefs = curriculum.flatMap((section) =>
  section.chapters.flatMap((chapter) =>
    chapter.lessons.map((ref) => ({ section, chapter, ref })),
  ),
)

export function countLessons(section: Section): number {
  return section.chapters.reduce((total, chapter) => total + chapter.lessons.length, 0)
}

export const totalLessonCount = curriculum.reduce(
  (total, section) => total + countLessons(section),
  0,
)
