import type { Chapter, LessonKind, Section, SectionAccent, SectionIcon } from './types'

/** [chapterTitle, chapterSummary, tenLessonTitles] */
type ChapterSeed = [string, string, string[]]

interface SectionSeed {
  title: string
  tagline: string
  description: string
  accent: SectionAccent
  icon: SectionIcon
  chapters: ChapterSeed[]
}

const pad = (value: number) => String(value).padStart(2, '0')

/**
 * The last node of every chapter is a checkpoint; the very last node of a section is its boss
 * project. Nodes explicitly titled "Prática:" are extra reps on an already taught concept.
 */
function kindFor(title: string, lessonIndex: number, isLastChapter: boolean): LessonKind {
  if (lessonIndex === 9) return isLastChapter ? 'boss' : 'checkpoint'
  if (title.startsWith('Prática:')) return 'practice'
  return 'lesson'
}

function buildChapters(sectionId: string, seeds: ChapterSeed[]): Chapter[] {
  return seeds.map(([title, summary, lessons], chapterIndex) => {
    const chapterId = `${sectionId}c${pad(chapterIndex + 1)}`
    const isLastChapter = chapterIndex === seeds.length - 1

    return {
      id: chapterId,
      title,
      summary,
      lessons: lessons.map((lessonTitle, lessonIndex) => ({
        id: `${chapterId}l${pad(lessonIndex + 1)}`,
        title: lessonTitle,
        kind: kindFor(lessonTitle, lessonIndex, isLastChapter),
      })),
    }
  })
}

